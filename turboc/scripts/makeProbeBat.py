#!/usr/bin/env python3
"""Make a probe batch from a generated compile batch of the 8.3 layout.

The compile batches made by map_to_83.py (BASE.BAT, BASE86.BAT) stop at the
first file that does not compile, and Turbo C++ needs some 20 minutes for the
whole base library, so finding the errors one by one costs a run per error.
The probe batch compiles every object without stopping and appends only the
error lines of each failed file to PROBE.LOG (next to the batch, inside
C:\\VITRAL).  Read it in DOS with `find /c "Error" PROBE.LOG` and
`find "Error" PROBE.LOG | more`; the objects of the files that compile are
kept, but run the real batch (then its link batch) once the probe is clean.

Usage, on a staging folder of stageDosFull.sh:
    python3 scripts/makeProbeBat.py <stage>/TURBOC/BASE/BASE.BAT <stage>/TURBOC/BASE/PROBE.BAT
"""
import sys


def make_probe(source, target):
    lines = open(source, "rb").read().decode("latin-1").replace("\r\n", "\n").split("\n")
    out = ["@echo off",
           "rem Generated by scripts/makeProbeBat.py: compiles every object without",
           "rem stopping; the error lines of the failed files go to PROBE.LOG.",
           "if exist PROBE.LOG del PROBE.LOG"]
    for line in lines[1:]:
        if line.startswith("if errorlevel 1 goto error"):
            out.append('if errorlevel 1 find "Error" TC.LOG >> PROBE.LOG')
        elif line.startswith("if not exist BUILDTC\\") and line.endswith("goto error"):
            continue
        elif line.startswith(":error") or line.startswith("goto end"):
            break
        else:
            out.append(line)
    out += ["echo PROBE_DONE >> PROBE.LOG", "echo Probe finished: see PROBE.LOG"]
    open(target, "wb").write(("\r\n".join(out) + "\r\n").encode("latin-1"))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    make_probe(sys.argv[1], sys.argv[2])
