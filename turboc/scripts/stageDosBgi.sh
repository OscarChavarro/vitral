#!/bin/sh
# Stage long-name host sources of the BGI SceneEditorApplication (real mode DOS),
# map only the copy, and package the DOS components: the base library, the XMS
# services of dos, the bgi library, testsuite/BGIExamples/SceneEditorApplication
# and the GUI definitions of etc/gui.  Prints the staging folder, which holds
# VITRAL.TGZ and VITRAL.ISO (see the README, "Validated DOS VM transfer
# procedure").
set -eu
if [ "$#" -ne 0 ]; then
    echo 'Usage: sh scripts/stageDosBgi.sh' >&2
    exit 2
fi
port_root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
stage_root=$(mktemp -d /tmp/vitralbgi-stage.XXXXXX)
cp -a "$port_root" "$stage_root/TURBOC"
mkdir -p "$stage_root/etc"
cp -a "$port_root/../etc/gui" "$stage_root/etc/gui"
# These are generated by map_to_83 and collide on a case-insensitive volume.
mv "$stage_root/TURBOC/base/base.bat" "$stage_root/base.bat"
mv "$stage_root/TURBOC/base/baselink.bat" "$stage_root/baselink.bat"
(
    cd "$stage_root/TURBOC"
    python3 scripts/map_to_83.py --clang clang > "$stage_root/MAPPING.LOG" 2>&1
)
# COMMAND.COM requires CRLF for batch files; keep host sources in Unix format.
python3 - "$stage_root/TURBOC" <<'PYDOS'
from pathlib import Path
import sys
for path in Path(sys.argv[1]).rglob('*'):
    if path.is_file() and path.suffix.lower() == '.bat':
        data = path.read_bytes().replace(b'\r\n', b'\n').replace(b'\r', b'\n')
        path.write_bytes(data.replace(b'\n', b'\r\n'))
PYDOS
python3 "$port_root/scripts/validateDos83.py" "$stage_root/TURBOC" BASE DOS BGI TESTSUIT/BGIEXAM/SCENEDIT
tar -czf "$stage_root/VITRAL.TGZ" --exclude='*/BUILD' --exclude='*/BUILDTC' --exclude='*/BUILD86' \
    -C "$stage_root" \
    TURBOC/BASE TURBOC/DOS TURBOC/BGI TURBOC/TESTSUIT/BGIEXAM/SCENEDIT ETC/GUI
mkisofs -quiet -iso-level 1 -o "$stage_root/VITRAL.ISO" \
    -graft-points "VITRAL.TGZ=$stage_root/VITRAL.TGZ"
printf '%s\n' "$stage_root"
