#!/usr/bin/env python3
# Renames the turboc port from its long names to DOS names, for Turbo C++ 3.0:
#   1. class names longer than 32 characters (class_renames_32.csv), changing
#      only identifier tokens, as found by the raw lexer of clang
#   2. quoted (and <> ones that name files of the port) #include directives
#   3. text of the sources to DOS (CRLF) line endings
#   4. files to 8.3 names (mappings_83.csv)
#   5. folders to 8.3 names
#   6. generates the files of the Turbo C++ build: java/io/NAMES83.H, the
#      table of the 8.3 names of the data files of ../etc (also in
#      mappings_83.csv) for File::toPlatformName, and the Borland MAKE files
#      of the base library (base/BASE.MAK, from the SOURCES of base/Makefile)
#      and of each offline example (<example>/<EXAMPLE>.MAK).  BASE.BAT
#      compiles the base objects and BASELINK.BAT archives the existing
#      objects; keeping them separate makes the DOS linker retryable.
# map_from_83.py does the inverse. The parts of the port that are not in the
# tables (i.e. the X11, OpenGL and svgalib ones) are not changed.
