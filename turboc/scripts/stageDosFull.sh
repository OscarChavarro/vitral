#!/bin/sh
# Stage the complete DOS payload: every file of etc/ and of the turboc port that
# has an 8.3 mapping, mapped by map_to_83.py.  Unlike stageDos286.sh and
# stageDosBgi.sh, which package one program, this builds the tree for a full
# replacement of C:\VITRAL (both the 286 raytracer and the real mode BGI
# programs).  Only files tracked by git are copied, and etc/portMachines (the
# test node credentials) never is.  Files whose path is not 8.3 after the
# mapping (the X11, OpenGL and svgalib parts, host scripts) are left out, as
# well as build folders.  Prints the staging folder, which holds FILES.LST,
# VITRAL.TGZ and VITRAL.ISO (see the README, "Validated DOS VM transfer
# procedure").
set -eu
if [ "$#" -ne 0 ]; then
    echo 'Usage: sh scripts/stageDosFull.sh' >&2
    exit 2
fi
port_root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
repo_root=$(CDPATH= cd -- "$port_root/.." && pwd)
stage_root=$(mktemp -d /tmp/vitralfull-stage.XXXXXX)
mkdir -p "$stage_root/TURBOC" "$stage_root/etc" "$stage_root/iso"
(cd "$repo_root" && git ls-files -co --exclude-standard turboc) | sed 's|^turboc/||' |
    (cd "$port_root" && cpio -pdm --quiet "$stage_root/TURBOC")
(cd "$repo_root" && git ls-files etc) | grep -v '^etc/portMachines/' | sed 's|^etc/||' |
    (cd "$repo_root/etc" && cpio -pdm --quiet "$stage_root/etc")
# These are generated by map_to_83 and collide on a case-insensitive volume.
mv "$stage_root/TURBOC/base/base.bat" "$stage_root/base.bat"
mv "$stage_root/TURBOC/base/baselink.bat" "$stage_root/baselink.bat"
(
    cd "$stage_root/TURBOC"
    python3 scripts/map_to_83.py --clang clang > "$stage_root/MAPPING.LOG" 2>&1
)
# The RUN*.BAT files of the raytracer read their scenes from the top of ETC
# (the names of stageDos286.sh); heightfield_terrain.ray reads TERRAIN.ALT.
for scene in balls:BALLS balls_featured_object:APPEL3 bezier_patches:BEZIPATC blob_molecule:BLOBMOLE \
    box_offsets:BOXOFFSE csg_lens:CSGLENS csg_sculpture:CSGSCULP csg_sculpture_pov:CSGSCUPO \
    csg_union_pov:CSGUNIPO glass_lens:GLASLENS halfspace_sloped:HALFSLOP heightfield_terrain:HEIGTERR \
    poly_surfaces:POLYSURF quadric_cylinder:QUADCYLI quadric_ellipsoid:QUADELLI \
    quadric_hyperboloid:QUADHYPE quadric_pair:QUADPAIR quadric_paraboloid:QUADPARA \
    quadric_rotated_ellipsoid:QUAROTEL quadric_saddle:QUADSADD sboard:SBOARD test:TEST; do
    cp "$repo_root/etc/geometry/mitscenes/${scene%%:*}.ray" "$stage_root/ETC/${scene##*:}.RAY"
done
cp "$repo_root/etc/geometry/mitscenes/terrain.alt" "$stage_root/ETC/TERRAIN.ALT"
# Keep the 8.3 files, check DOS name collisions and give batch files CRLF.
python3 - "$stage_root" <<'PYDOS'
import re
import sys
from pathlib import Path
root = Path(sys.argv[1])
name83 = re.compile(r"[A-Za-z0-9_$~-]{1,8}(\.[A-Za-z0-9_$~-]{1,3})?")
skipped_dirs = {"BUILD", "BUILDTC", "BUILD86", "__PYCACHE__"}
keep = []
skipped = 0
seen = {}
for top in ("ETC", "TURBOC"):
    for path in sorted((root / top).rglob("*")):
        if not path.is_file():
            continue
        relative = path.relative_to(root)
        parts = relative.parts
        if (not all(name83.fullmatch(part) for part in parts)
                or any(part.upper() in skipped_dirs for part in parts)
                or relative.name.upper() == "OUTPUT.PPM"):
            skipped += 1
            continue
        key = relative.as_posix().upper()
        if key in seen:
            sys.exit("DOS name collision: " + seen[key] + " / " + relative.as_posix())
        seen[key] = relative.as_posix()
        if path.suffix.upper() == ".BAT":
            data = path.read_bytes().replace(b"\r\n", b"\n").replace(b"\r", b"\n")
            path.write_bytes(data.replace(b"\n", b"\r\n"))
        keep.append(relative.as_posix())
(root / "FILES.LST").write_text("\n".join(keep) + "\n")
print("%d files staged, %d left out" % (len(keep), skipped), file=sys.stderr)
PYDOS
python3 "$port_root/scripts/validateDos83.py" "$stage_root/TURBOC" BASE DOS BGI TESTSUIT/BGIEXAM \
    TESTSUIT/OFFLEXAM >&2
tar --format=gnu -czf "$stage_root/iso/VITRAL.TGZ" -C "$stage_root" -T "$stage_root/FILES.LST"
mkisofs -quiet -iso-level 1 -V VITRAL83 -o "$stage_root/VITRAL.ISO" "$stage_root/iso"
printf '%s\n' "$stage_root"
