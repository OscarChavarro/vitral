#!/usr/bin/env python3
"""Make a batch that recompiles some base sources and updates their libraries.

After a small change, rerunning BASE.BAT (some 20 minutes in Turbo C++) and
BASELINK.BAT is not needed: this batch repeats only the compile steps of the
given objects (with the same options as BASE.BAT) and replaces them in the
libraries where BASELINK.BAT puts them (`tlib -+`, which also adds a new
object). Then relink the programs. Run it from C:\\VITRAL\\TURBOC\\BASE.

Usage, on a staging folder of stageDosFull.sh (8.3 object names):
    python3 scripts/makeUpdateBat.py <stage>/TURBOC/BASE UPDATE.BAT FILE ENVIPERS
writes <stage>/TURBOC/BASE/UPDATE.BAT; send it with the next patch (add it to
the FILES.LST of the staging folder).
"""
import re
import sys
from pathlib import Path


def read(path):
    return path.read_bytes().decode("latin-1").replace("\r\n", "\n").split("\n")


def compile_block(lines, name):
    """Lines of BASE.BAT that compile BUILDTC\\<name>.OBJ"""
    start = next(i for i, line in enumerate(lines)
                 if line.startswith("echo [") and re.search(r"\\" + name + r"\.CPP$", line))
    end = next(i for i in range(start, len(lines)) if lines[i].startswith("tcc "))
    return [line for line in lines[start + 1:end + 1]]


def library_of(lines, name):
    for line in lines:
        match = re.match(r"tlib (BUILD\\\w+\.LIB) .*\+BUILDTC\\" + name + r"\.OBJ ", line)
        if match:
            return match.group(1)
    raise SystemExit("%s.OBJ is in no library of BASELINK.BAT" % name)


def main():
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    base = Path(sys.argv[1])
    names = [name.upper() for name in sys.argv[3:]]
    compiling = read(base / "BASE.BAT")
    linking = read(base / "BASELINK.BAT")
    out = ["@echo off", "rem Generated by scripts/makeUpdateBat.py: recompiles " + " ".join(names)]
    for name in names:
        out.append("echo Compiling %s" % name)
        out += compile_block(compiling, name)
        # TCC 3.0 ends with errorlevel 0 when it dies with a GP fault
        out += ["if errorlevel 1 goto compile_error",
                "if not exist BUILDTC\\%s.OBJ goto compile_error" % name]
    for name in names:
        library = library_of(linking, name)
        out += ["echo %s update %s.OBJ" % (library, name),
                "tlib %s /C /E /P64 -+BUILDTC\\%s.OBJ > TLIB.LOG" % (library, name),
                'find "Error:" TLIB.LOG > NUL',
                "if not errorlevel 1 goto library_error"]
    out += ["echo Objects and libraries updated.", "goto end",
            ":compile_error", "type TC.LOG", "echo Compilation failed.", "goto end",
            ":library_error", "type TLIB.LOG", "echo Library update failed.", ":end"]
    (base / sys.argv[2]).write_bytes(("\r\n".join(out) + "\r\n").encode("latin-1"))


if __name__ == "__main__":
    main()
