#!/usr/bin/env python3
"""Generate deterministic exact binary64 comparison fixtures with Fraction."""
from fractions import Fraction
import math
from pathlib import Path
import random
import struct

random_source = random.Random(0x435347)


def value():
    while True:
        v = struct.unpack('>d', random_source.getrandbits(64).to_bytes(8, 'big'))[0]
        if math.isfinite(v):
            return v


def fraction(number):
    return Fraction.from_float(number)


def literal(number):
    return repr(number)


def product_line(a, b, c, d):
    expected = fraction(a) * fraction(b) == fraction(c) * fraction(d)
    values = ','.join(literal(x) for x in (a, b, c, d))
    return f'EXPECT_EQ({str(expected).lower()},CsgExactArithmetic::equalProducts({values}));'


def affine_line(a, b, c, d, e, f):
    expected = fraction(a) * fraction(b) + fraction(c) == fraction(d) * fraction(e) + fraction(f)
    values = ','.join(literal(x) for x in (a, b, c, d, e, f))
    return f'EXPECT_EQ({str(expected).lower()},CsgExactArithmetic::equalAffine({values}));'


lines = ['// Generated by generate_csg_exact_reference.py; include inside a test.']
for _ in range(200):
    a, b = value(), value()
    lines.append(product_line(a, b, b, a))
    rounded = a * b
    if math.isfinite(rounded):
        lines.append(product_line(a, b, rounded, 1.0))
    lines.append(product_line(a, b, value(), value()))
for _ in range(200):
    a, b, c = value(), value(), value()
    lines.append(affine_line(a, b, c, b, a, c))
    adjacent = math.nextafter(c, math.inf)
    if math.isfinite(adjacent):
        lines.append(affine_line(a, b, c, a, b, adjacent))
    lines.append(affine_line(a, b, c, value(), value(), value()))
for _ in range(200):
    a = [value() for _ in range(3)]
    b = [value() for _ in range(3)]
    c, d = list(reversed(a)), list(reversed(b))
    if random_source.randrange(2):
        candidate = math.nextafter(c[0], math.inf)
        if math.isfinite(candidate):
            c[0] = candidate
    expected = sum((fraction(x) * fraction(y) for x, y in zip(a, b)), Fraction()) == sum(
        (fraction(x) * fraction(y) for x, y in zip(c, d)), Fraction())
    arrays = [','.join(literal(v) for v in values) for values in (a, b, c, d)]
    lines.append('{const double a[3]={' + arrays[0] + '},b[3]={' + arrays[1] +
                 '},c[3]={' + arrays[2] + '},d[3]={' + arrays[3] +
                 '}; EXPECT_EQ(' + str(expected).lower() + ',CsgExactArithmetic::equalSumProducts(a,b,c,d,3));}')
Path(__file__).with_name('csg_exact_reference.inc').write_text('\n'.join(lines) + '\n')
