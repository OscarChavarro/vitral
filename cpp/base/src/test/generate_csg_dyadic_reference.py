#!/usr/bin/env python3
"""Generate exact multi-product identities from independent Fraction values."""
from fractions import Fraction
from pathlib import Path
import math
import random
import struct

rng = random.Random(0x445941)
rows = []
expected_values = []

def sample():
    while True:
        result = struct.unpack('>d', rng.getrandbits(64).to_bytes(8, 'big'))[0]
        if math.isfinite(result):
            return result

for case in range(300):
    a,b,c,d = (sample() for _ in range(4))
    if case < 200:
        e,f,g,h = c,d,a,b
        if case % 2:
            candidate = math.nextafter(e, math.inf)
            if math.isfinite(candidate):
                e = candidate
    else:
        e,f,g,h = (sample() for _ in range(4))
    exact = lambda x: Fraction.from_float(x)
    expected = exact(a)*exact(b)+exact(c)*exact(d)==exact(e)*exact(f)+exact(g)*exact(h)
    values = ','.join(repr(x) for x in (a,b,c,d,e,f,g,h))
    rows.append('{' + values + '}')
    expected_values.append(str(expected).lower())

lines = ['// Generated by generate_csg_dyadic_reference.py; include inside a test.',
         'static const double samples[][8]={' + ',\n'.join(rows) + '};',
         'static const bool expected[]={' + ','.join(expected_values) + '};',
         'for (int caseIndex=0;caseIndex<300;++caseIndex) {',
         '    CsgDyadic x[8],l1,l2,r1,r2,l,r;',
         '    for(int i=0;i<8;++i) ASSERT_TRUE(CsgDyadic::fromDouble(samples[caseIndex][i],x[i]));',
         '    ASSERT_TRUE(CsgDyadic::multiply(x[0],x[1],l1)); ASSERT_TRUE(CsgDyadic::multiply(x[2],x[3],l2));',
         '    ASSERT_TRUE(CsgDyadic::multiply(x[4],x[5],r1)); ASSERT_TRUE(CsgDyadic::multiply(x[6],x[7],r2));',
         '    ASSERT_TRUE(CsgDyadic::add(l1,l2,l)); ASSERT_TRUE(CsgDyadic::add(r1,r2,r));',
         '    EXPECT_EQ(expected[caseIndex],l.equals(r));',
         '    CsgDyadic combinedLeft,combinedRight,p00,p01,p10,p11,t0,t1;',
         '    ASSERT_TRUE(CsgDyadic::multiply(l,r,combinedLeft));',
         '    ASSERT_TRUE(CsgDyadic::multiply(l1,r1,p00)); ASSERT_TRUE(CsgDyadic::multiply(l1,r2,p01));',
         '    ASSERT_TRUE(CsgDyadic::multiply(l2,r1,p10)); ASSERT_TRUE(CsgDyadic::multiply(l2,r2,p11));',
         '    ASSERT_TRUE(CsgDyadic::add(p00,p01,t0)); ASSERT_TRUE(CsgDyadic::add(p10,p11,t1));',
         '    ASSERT_TRUE(CsgDyadic::add(t0,t1,combinedRight)); EXPECT_TRUE(combinedLeft.equals(combinedRight));',
         '}']
Path(__file__).with_name('csg_dyadic_reference.inc').write_text('\n'.join(lines) + '\n')
